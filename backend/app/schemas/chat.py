from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field
from app.schemas.common import AssistantIdentifier, LanguageCode, Source


class ChatRequest(BaseModel):
    model_config = ConfigDict(extra="ignore")

    message: str = Field(..., min_length=1, description="Citizen inquiry message")
    assistant: AssistantIdentifier = Field(
        ...,
        description="Target specialist assistant: agriculture, healthcare, education, or schemes",
    )
    language: LanguageCode = Field(
        ...,
        description="Communication language code: en (English) or te (Telugu)",
    )
    state: Optional[str] = Field(
        default=None,
        description="Citizen state, e.g. Andhra Pradesh",
    )
    district: Optional[str] = Field(
        default=None,
        description="Citizen district, e.g. Kakinada",
    )
    conversation_id: Optional[str] = Field(
        default=None,
        description="Optional conversation identifier; generated by backend if omitted",
    )


class ChatResponse(BaseModel):
    model_config = ConfigDict(extra="ignore")

    conversation_id: str = Field(..., description="Unique conversation session identifier")
    answer: str = Field(..., description="Response answer content in requested language")
    assistant: AssistantIdentifier = Field(..., description="Specialist assistant that handled query")
    language: LanguageCode = Field(..., description="Language code of response")
    sources: List[Source] = Field(
        default_factory=list,
        description="List of verified government and authoritative sources",
    )
    needs_follow_up: bool = Field(
        default=False,
        description="Indicates whether citizen needs to provide further clarification",
    )
    follow_up_questions: List[str] = Field(
        default_factory=list,
        description="Recommended follow-up questions for the citizen",
    )
    safety_notice: Optional[str] = Field(
        default=None,
        description="Domain-specific advisory or emergency guidance if applicable",
    )
    service_action: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional interactive action payload for navigating to nearby services or tools",
    )
